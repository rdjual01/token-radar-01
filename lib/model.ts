// Token Radar model "radar-2": category-comps implied value.
//
// The starter's flat 0.25x TVL treats a lending market and a perps exchange as the same
// business. This model prices each protocol against the tokens that already trade in its
// own category: the median market-cap-per-TVL of live-token protocols in that category,
// shrunk toward the market-wide median when the category has few live comps, and capped
// so one outlier cannot set the price. Growth, maturity and chain breadth then adjust it.
// Everything comes from the sealed snapshot alone; no protocol name is special-cased.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

